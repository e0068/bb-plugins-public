/**
 * Очередь на ключ: вызовы с одним ключом идут строго по одному, с разными —
 * параллельно. Нужна там, где «прочитать номера доски и записать файл» обязано
 * быть неделимым: два одновременных запроса, прочитавшие один и тот же
 * наибольший номер, выдали бы задачам один ключ. Процесс плагина один, поэтому
 * очереди в памяти достаточно — файлового замка не требуется.
 *
 * Карта хвостов не чистится намеренно: ключей в ней столько же, сколько досок,
 * а доска живёт всё время работы плагина.
 */
export function createSerialByKey() {
  const tails = new Map<string, Promise<unknown>>();

  return function serial<T>(key: string, run: () => Promise<T>): Promise<T> {
    // Хвост держит только момент завершения, не исход: он всегда пойман
    // ниже, поэтому упавший вызов не отменяет следующего.
    const previous = tails.get(key) ?? Promise.resolve();
    const result = previous.then(run);
    tails.set(
      key,
      result.catch(() => undefined),
    );
    return result;
  };
}
