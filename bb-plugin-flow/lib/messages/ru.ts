const quote = (text: string): string => `«${text}»`;

/** Число со словом в нужной форме: 1 и 21 — `one`, 2–4 и 22 — `few`, остальное и 11–14 — `many`. */
const plural = (n: number, one: string, few: string, many: string): string => {
  const tens = n % 100;
  const units = n % 10;
  const word = units === 1 && tens !== 11 ? one : units >= 2 && units <= 4 && (tens < 12 || tens > 14) ? few : many;
  return `${n} ${word}`;
};

