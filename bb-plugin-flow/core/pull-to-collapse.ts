// Раскрытый список этапов баннера прогресса — своя область прокрутки. Когда он
// стоит в самом верху, листать дальше некуда, и то же движение вниз тянет сам
// баннер: список едет за пальцем и на отпускании либо доезжает вниз до конца,
// либо возвращается на место. Баннер прижат к композеру снизу, поэтому «ехать
// за пальцем» — это уменьшать высоту списка: его верхний край идёт вниз.

/** Доля высоты списка, после которой отпущенный палец оставляет баннер закрытым. Как у шторок кита. */
export const PULL_CLOSE_RATIO = 0.25;

/** Сколько длится доводка после отпускания, мс. Столько же и у шторок кита. */
export const PULL_SETTLE_MS = 220;

/** Положение списка, пройденное пальцем вниз расстояние и высота списка в пикселях. */
export interface Pull {
  scrollTop: number;
  movedDown: number;
  height: number;
}

/** На сколько список уехал за пальцем: ноль, пока список не в самом верху или палец идёт вверх; дальше своей высоты список не уезжает. */
export const pullOffset = ({ scrollTop, movedDown, height }: Pull): number =>
  scrollTop > 0 ? 0 : Math.min(Math.max(0, movedDown), Math.max(0, height));

/** Останется ли баннер закрытым, если палец отпустили на этом смещении. */
export const settlesClosed = ({ offset, height }: { offset: number; height: number }): boolean =>
  height > 0 && offset >= height * PULL_CLOSE_RATIO;
