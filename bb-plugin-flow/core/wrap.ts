// Ряды кнопок, перенесённых flex-контейнером: раскрытый список встаёт сразу
// под рядом своей кнопки, а какой это ряд, знает только раскладка. Здесь —
// чистая часть: по верхним краям кнопок найти последнюю кнопку каждого ряда.

/** Кнопки с одинаковым верхним краем стоят в одном ряду; для каждой — номер последней кнопки её ряда. */
export const rowEnds = (tops: readonly number[]): number[] =>
  tops.map((top, i) => {
    let end = i;
    while (end + 1 < tops.length && Math.abs(tops[end + 1]! - top) < 2) end += 1;
    return end;
  });
