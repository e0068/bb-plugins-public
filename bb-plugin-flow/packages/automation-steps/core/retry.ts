// Слой 1 — что считать временной ошибкой шага и сколько ждать перед повтором.
// Эффектов нет: обе величины — значения, повтор по ним делает steps.ts.
//
// Повторяется только то, что проходит само: GitHub, который ещё считает
// (409 на mergeability сразу после переписанной головы PR) или ещё не видит
// (404 на ветку, только что созданную через API), перегруженный или
// приболевший GitHub (429, 5xx), обрыв сети и проигранная гонка за git-ссылку:
// деревья тредов делят ссылки с основной копией, и соседний fetch двигает
// origin/main посреди нашего — повтор через пару секунд проходит. Всё остальное считается
// постоянным — конфликт слияния, отсутствие токена, закрытый PR, — потому что
// повтор такой ошибки не лечит, а только оттягивает её показ владельцу.
// Умолчание именно такое: неизвестный текст ошибки не повторяется, иначе шаг
// с эффектом молча выполнился бы дважды.

export type FailureKind = "transient" | "permanent";

/** Паузы перед повторами: две паузы — до трёх попыток на шаг. */
export const RETRY_DELAYS_MS: readonly number[] = [2_000, 8_000];

const TRANSIENT = [
  /HTTP 5\d\d/,
  /HTTP 429/,
  /HTTP 408/,
  /HTTP 404/,
  /HTTP 409/,
  /fetch failed/i,
  /socket hang up/i,
  /ECONNRESET/,
  /ETIMEDOUT/,
  /ECONNREFUSED/,
  /EAI_AGAIN/,
  /ENOTFOUND/,
  /cannot lock ref/,
];

export const classifyFailure = (error: string): FailureKind =>
  TRANSIENT.some((pattern) => pattern.test(error)) ? "transient" : "permanent";
